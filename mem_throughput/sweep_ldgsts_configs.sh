#     "1 1 1024"
#     "1 2 512"
#     "1 4 256"
#     "2 1 512"
#     "2 2 256"
#     "2 4 128"
#     "1 2 1024"
#     "1 4 512"
#     "2 1 1024"
#     "2 2 512"
#     "2 4 256"
#     "1 4 1024"
#     "2 2 1024"
#     "2 4 512"
#     "2 4 1024"
#     "2 5 1024"
#     "2 6 1024"
# 8B loads
#     "1 1 128"
