OUTPUT_FILE="ldgsts${LOAD_SIZE}b_sweep_results.csv"

echo "load_size, ctas_per_sm, num_stages, tds_per_cta, throughput" > "$OUTPUT_FILE"

for combo in "${COMBINATIONS[@]}"; do
    read -r CTAS_PER_SM NUM_STAGES THREADS_PER_BLOCK <<< "$combo"
    echo "Running: CTAS_PER_SM=$CTAS_PER_SM NUM_STAGES=$NUM_STAGES, THREADS_PER_BLOCK=$THREADS_PER_BLOCK"

    make clean
    make cp_async CTAS_PER_SM="$CTAS_PER_SM" NUM_STAGES="$NUM_STAGES" THREADS_PER_BLOCK="$THREADS_PER_BLOCK"
    BYTES_PER_SEC=$(
        sudo "$NCU_BIN" --clock-control none --csv --metrics dram__bytes_read.sum.per_second ./cp_async 2>/dev/null \
        | tail -1 | awk -F'","' '{print $NF}' | tr -d '"'
    )
    TB_PER_SEC=$(echo "$BYTES_PER_SEC" | awk '{printf "%.4f", $1 / 1e12}')

    echo "Memory Throughput: ${TB_PER_SEC} TB/s"
    echo "${CTAS_PER_SM},${NUM_STAGES},${THREADS_PER_BLOCK},${TB_PER_SEC}" >> "$OUTPUT_FILE"
done
